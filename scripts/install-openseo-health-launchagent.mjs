import { spawnSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const deadman = process.argv[4] === "--deadman";
const label = deadman
  ? "com.joelclaw.openseo-health-deadman"
  : "com.joelclaw.openseo-nightly-health";
const schedule = deadman
  ? "Hourly; alarm after 26h without main OTEL event"
  : "02:05 America/Los_Angeles";
const marker = "Generated by install-openseo-health-launchagent.mjs";
const escape = (value) =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
const configPath = process.argv[2];
const mode = process.argv[3] ?? "--check";
if (
  !configPath ||
  !["--check", "--apply"].includes(mode) ||
  (process.argv[4] && !deadman) ||
  process.argv.length > 5
)
  throw new Error(
    "Usage: node install-openseo-health-launchagent.mjs <private-config.json> --check|--apply [--deadman]",
  );
const zone = Intl.DateTimeFormat().resolvedOptions().timeZone;
if (!["America/Los_Angeles", "US/Pacific"].includes(zone))
  throw new Error(
    "02:05 scheduling requires this host's local timezone to be Pacific",
  );
const config = JSON.parse(await readFile(configPath, "utf8"));
if (typeof config.reportDir !== "string" || !config.reportDir.startsWith("/"))
  throw new Error("Config needs an absolute reportDir");
const target = join(homedir(), "Library", "LaunchAgents", `${label}.plist`);
const logDir = join(config.reportDir, "logs");
const script = join(
  dirname(fileURLToPath(import.meta.url)),
  deadman ? "openseo-health-deadman.mjs" : "openseo-nightly-health.mjs",
);
const path = [
  join(homedir(), ".local/bin"),
  join(homedir(), ".pi/agent/bin"),
  join(homedir(), ".bun/bin"),
  "/opt/homebrew/bin",
  "/usr/local/bin",
  "/usr/bin",
  "/bin",
  "/usr/sbin",
  "/sbin",
].join(":");
const fallbackEnvironment = {
  OPENSEO_HEALTH_REPORT_DIR: config.reportDir,
  OPENSEO_HEALTH_SENDER: config.sender,
  OPENSEO_HEALTH_RECIPIENT: config.recipient,
  OPENSEO_HEALTH_RATKING: config.ratking,
  OPENSEO_HEALTH_JOELCLAW: config.joelclaw,
  OPENSEO_HEALTH_SECRETS: config.secrets,
  OPENSEO_HEALTH_OTEL_TOKEN_SECRET: config.otelTokenSecret,
  OPENSEO_HEALTH_OTEL_INGEST: config.otelIngest,
  OPENSEO_HEALTH_SYSTEM_ID: config.systemId,
};
if (
  Object.values(fallbackEnvironment).some(
    (value) => typeof value !== "string" || !value,
  )
)
  throw new Error(
    "Installer requires complete non-secret fallback alarm configuration",
  );
const fallbackXml = Object.entries(fallbackEnvironment)
  .map(([key, value]) => `<key>${key}</key><string>${escape(value)}</string>`)
  .join("\n");
const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- ${marker} -->
<plist version="1.0"><dict>
<key>Label</key><string>${label}</string>
<key>ProgramArguments</key><array><string>${escape(config.nodeExecutable ?? process.execPath)}</string><string>${escape(script)}</string></array>
<key>WorkingDirectory</key><string>${escape(dirname(script))}</string>
<key>EnvironmentVariables</key><dict>
<key>HOME</key><string>${escape(homedir())}</string>
<key>PATH</key><string>${escape(path)}</string>
<key>OPENSEO_HEALTH_CONFIG</key><string>${escape(configPath)}</string>
<key>RATKING_NAME</key><string>off</string>
${fallbackXml}
</dict>
${deadman ? "<key>StartInterval</key><integer>3600</integer><key>RunAtLoad</key><true/>" : "<key>StartCalendarInterval</key><dict><key>Hour</key><integer>2</integer><key>Minute</key><integer>5</integer></dict><key>RunAtLoad</key><false/>"}
<key>ProcessType</key><string>Background</string>
<key>LowPriorityIO</key><true/>
<key>Nice</key><integer>10</integer>
<key>Umask</key><integer>63</integer>
<key>StandardOutPath</key><string>${escape(join(logDir, deadman ? "deadman.out.log" : "launchd.out.log"))}</string>
<key>StandardErrorPath</key><string>${escape(join(logDir, deadman ? "deadman.err.log" : "launchd.err.log"))}</string>
</dict></plist>\n`;
let existing;
try {
  existing = await readFile(target, "utf8");
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}
if (existing && !existing.includes(marker))
  throw new Error(
    "Existing LaunchAgent is not owned by this installer; nothing overwritten",
  );
const service = `gui/${process.getuid()}/${label}`;
const observed = spawnSync("launchctl", ["print", service], {
  encoding: "utf8",
});
if (mode === "--check") {
  console.info(
    JSON.stringify({
      label,
      schedule,
      configMatches: existing === plist,
      registered: observed.status === 0,
      target,
    }),
  );
  if (existing !== plist || observed.status !== 0) process.exitCode = 1;
} else {
  await mkdir(dirname(target), { recursive: true });
  await mkdir(logDir, { recursive: true, mode: 0o700 });
  if (existing !== plist && observed.status === 0) {
    const stopped = spawnSync("launchctl", ["bootout", service], {
      encoding: "utf8",
    });
    if (stopped.status !== 0)
      throw new Error("Could not unload the owned old LaunchAgent");
  }
  await writeFile(target, plist, { mode: 0o600 });
  const checked = spawnSync("plutil", ["-lint", target], { encoding: "utf8" });
  if (checked.status !== 0)
    throw new Error("Generated LaunchAgent failed plutil validation");
  if (observed.status !== 0 || existing !== plist) {
    const loaded = spawnSync(
      "launchctl",
      ["bootstrap", `gui/${process.getuid()}`, target],
      { encoding: "utf8" },
    );
    if (loaded.status !== 0)
      throw new Error("Could not register the owned LaunchAgent");
  }
  console.info(JSON.stringify({ label, schedule, installed: true, target }));
}
